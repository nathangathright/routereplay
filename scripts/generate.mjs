#!/usr/bin/env node
/**
 * Generate server modules under src/server/generated:
 * - content.ts embeds the agent workflow and reference and the acknowledgments; /agent-docs and /acknowledgments
 *   are rendered from them.
 * - airports.ts holds the airport table as one string, one airport per line (see src/server/airports/index.ts).
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const read = (p) => readFile(path.join(root, p), 'utf8');

async function emit(name, out) {
  const target = path.join(root, 'src/server/generated', name);
  await mkdir(path.dirname(target), { recursive: true });
  let previous = '';
  try {
    previous = await readFile(target, 'utf8');
  } catch {}
  if (previous !== out) await writeFile(target, out);
}

const workflow = await read('agent/workflow.md');
const reference = await read('agent/reference.md');
const docs = JSON.parse(await read('agent/docs.json'));
const acknowledgments = await read('src/server/acknowledgments.txt');

await emit(
  'content.ts',
  `// Generated by scripts/generate.mjs from agent/* and src/server/acknowledgments.txt. Do not edit.
export const WORKFLOW_MD = ${JSON.stringify(workflow)};
export const REFERENCE_MD = ${JSON.stringify(reference)};
export const DOCS_VERSION = ${JSON.stringify(docs.version)};
export const ACKNOWLEDGMENTS_TXT = ${JSON.stringify(acknowledgments)};
`,
);

// The lookup binary-searches the lines, so they must be sorted by code and free of tabs and newlines.
const airports = JSON.parse(await read('src/server/airports/airports.json'));
const fields = ['code', 'name', 'city', 'country', 'lat', 'lon', 'timeZone'];
if (airports.fields.join() !== fields.join()) throw new Error(`airports.json fields changed: ${airports.fields.join()}`);
let lines = '';
let previousCode = '';
for (const row of airports.rows) {
  const code = row[0];
  if (!/^[A-Z]{3}$/.test(code) || code <= previousCode) throw new Error(`airports.json: ${code} is not a code in sorted order`);
  if (row.some((f) => /[\t\n]/.test(String(f)))) throw new Error(`airports.json: ${code} has a tab or newline`);
  previousCode = code;
  lines += row.join('\t') + '\n';
}
await emit(
  'airports.ts',
  `// Generated by scripts/generate.mjs from src/server/airports/airports.json. Do not edit.
export const AIRPORT_DATA_VERSION = ${JSON.stringify(airports.version)};
/** One airport per line, sorted by code: ${fields.join(', ')}, separated by tabs. */
export const AIRPORT_LINES = ${JSON.stringify(lines)};
`,
);
