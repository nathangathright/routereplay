#!/usr/bin/env node
/**
 * Embed the agent workflow and reference, and the acknowledgments, into the server bundle;
 * /agent-docs and /acknowledgments are rendered from them.
 */
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const read = (p) => readFile(path.join(root, p), 'utf8');

const workflow = await read('agent/workflow.md');
const reference = await read('agent/reference.md');
const docs = JSON.parse(await read('agent/docs.json'));
const acknowledgments = await read('src/server/acknowledgments.txt');

const out = `// Generated by scripts/generate.mjs from agent/* and src/server/acknowledgments.txt. Do not edit.
export const WORKFLOW_MD = ${JSON.stringify(workflow)};
export const REFERENCE_MD = ${JSON.stringify(reference)};
export const DOCS_VERSION = ${JSON.stringify(docs.version)};
export const ACKNOWLEDGMENTS_TXT = ${JSON.stringify(acknowledgments)};
`;
const target = path.join(root, 'src/server/generated/content.ts');
await mkdir(path.dirname(target), { recursive: true });
let previous = '';
try {
  previous = await readFile(target, 'utf8');
} catch {}
if (previous !== out) await writeFile(target, out);
